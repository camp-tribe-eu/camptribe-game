// Те саме, що світло ліхтарів і вогнища: один радіальний градієнт з канви (без файлів графіки), ADD над нічною маскою — він ПІДСВІЧУЄ темряву.
// Сила — від темряви доби (daylight.ts): вдень 0 (картинка ідентична), глибока ніч — максимум. Темрява сама не змінюється (таблиця ключів власника).
import { MAX_DARKNESS } from './daylight';

/** Радіус кола, px: 2,75 тайла (тайл 32 px) — у межах 2,5–3 тайлів із картки. */
export const HERO_LIGHT_RADIUS = 88;
/** Найбільша прозорість кола вночі (ADD над маскою). */
export const HERO_LIGHT_MAX_ALPHA = 0.6;

/** Прозорість кола героя за темрявою доби: 0 вдень, зростає монотонно, вночі — HERO_LIGHT_MAX_ALPHA. */
export function heroLightAlpha(darkness: number): number {
  if (!(darkness > 0)) return 0;
  return Math.min(1, darkness / MAX_DARKNESS) * HERO_LIGHT_MAX_ALPHA;
}
