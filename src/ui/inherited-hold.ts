// GAME-237 · «успадкований» палець рамки розмови: вказівники, притиснуті в мить її появи (кнопка «дія» на мапі). Поки хоч один не піднято,
// рамка глуха для дотику й миші — «клік» від підняття не обирає відповідь під пальцем. Чисті правила, щоб їх можна було перевірити без DOM.

/** Чи глуха рамка для цієї події. Клавіатура — ніколи: «клік від підняття» буває лише у вказівника, а загублений pointerup (мишу
 *  відпустили за вікном) не має замикати вибір клавішами. */
export function heldBlocks(eventType: string, inherited: ReadonlySet<number> | null): boolean {
  if (eventType.startsWith('key')) return false;
  return (inherited?.size ?? 0) > 0;
}

/** Нове натискання після появи рамки: той самий палець не може натиснути вдруге, не піднявшись, — отже всі успадковані вже підняті
 *  (навіть якщо їх pointerup загубився). Чистимо, щоб рамка не лишилась глухою назавжди. */
export function freshPress(inherited: Set<number> | null): void {
  inherited?.clear();
}
